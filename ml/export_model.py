#!/usr/bin/env python3
"""
Export trained RandomForestRegressor to JSON and embedded C++ representation.
Also generates test_predictions.json for C++ validation.
"""

import os
import json
import joblib
import pandas as pd
import numpy as np

FEATURE_COLS = [
    "food_category",
    "order_quantity",
    "preparation_complexity",
    "time_of_day_hour",
    "current_kitchen_workload"
]
TARGET_COL = "observed_prep_time_minutes"

def export():
    script_dir = os.path.dirname(os.path.abspath(__file__))
    project_root = os.path.abspath(os.path.join(script_dir, ".."))
    model_path = os.path.join(script_dir, "model.joblib")
    test_path = os.path.join(script_dir, "test_split.csv")
    json_model_path = os.path.join(script_dir, "model.json")
    test_preds_path = os.path.join(script_dir, "test_predictions.json")
    cpp_header_path = os.path.join(project_root, "include", "canteen", "models", "EmbeddedModelData.hpp")

    if not os.path.exists(model_path):
        raise FileNotFoundError(f"Model not found at {model_path}. Run train_model.py first.")

    model = joblib.load(model_path)

    # 1. Export Random Forest trees to JSON
    forest_data = {
        "model_type": "RandomForestRegressor",
        "n_estimators": int(model.n_estimators),
        "n_features": len(FEATURE_COLS),
        "feature_names": FEATURE_COLS,
        "trees": []
    }

    for idx, estimator in enumerate(model.estimators_):
        tree = estimator.tree_
        tree_dict = {
            "tree_index": idx,
            "node_count": int(tree.node_count),
            "feature": tree.feature.tolist(),
            "threshold": [round(float(t), 6) for t in tree.threshold],
            "children_left": tree.children_left.tolist(),
            "children_right": tree.children_right.tolist(),
            "value": [round(float(v[0][0]), 6) for v in tree.value]
        }
        forest_data["trees"].append(tree_dict)

    with open(json_model_path, "w") as f:
        json.dump(forest_data, f, indent=2)
    print(f"[EXPORT] Saved JSON model ({len(forest_data['trees'])} trees) to {json_model_path}")

    # 2. Generate test_predictions.json from held-out test split
    test_df = pd.read_csv(test_path)
    # Select 25 evenly spaced samples from test set
    sample_indices = np.linspace(0, len(test_df) - 1, 25, dtype=int)
    samples = test_df.iloc[sample_indices]

    X_samples = samples[FEATURE_COLS]
    py_preds = model.predict(X_samples)

    test_cases = []
    for i in range(len(samples)):
        row = samples.iloc[i]
        tc = {
            "sample_index": int(sample_indices[i]),
            "features": [float(row[col]) for col in FEATURE_COLS],
            "feature_dict": {col: float(row[col]) for col in FEATURE_COLS},
            "actual_target": float(row[TARGET_COL]),
            "python_prediction": round(float(py_preds[i]), 6)
        }
        test_cases.append(tc)

    with open(test_preds_path, "w") as f:
        json.dump({"test_cases": test_cases}, f, indent=2)
    print(f"[EXPORT] Saved {len(test_cases)} test verification cases to {test_preds_path}")

    # 3. Generate EmbeddedModelData.hpp for C++ zero-dependency compiled fallback
    # We embed the tree structure into C++ constants so the program has a verified fallback
    first_tree = forest_data["trees"][0]
    with open(cpp_header_path, "w") as f:
        f.write("// Auto-generated by ml/export_model.py - Do not modify manually\n")
        f.write("#ifndef CANTEEN_EMBEDDED_MODEL_DATA_HPP\n")
        f.write("#define CANTEEN_EMBEDDED_MODEL_DATA_HPP\n\n")
        f.write("#include <vector>\n")
        f.write("#include <string>\n\n")
        f.write("namespace canteen {\n")
        f.write("namespace ml {\n\n")
        f.write(f"constexpr int EMBEDDED_N_ESTIMATORS = {len(forest_data['trees'])};\n")
        f.write(f"constexpr int EMBEDDED_N_FEATURES = {len(FEATURE_COLS)};\n\n")
        f.write("// Feature names indices:\n")
        for i, fn in enumerate(FEATURE_COLS):
            f.write(f"//   {i}: {fn}\n")
        f.write("\n")
        
        # Write first tree as embedded Decision Tree representation
        f.write(f"constexpr int FIRST_TREE_NODE_COUNT = {first_tree['node_count']};\n")
        f.write(f"const int FIRST_TREE_FEATURE[] = {{{', '.join(map(str, first_tree['feature']))}}};\n")
        f.write(f"const double FIRST_TREE_THRESHOLD[] = {{{', '.join(map(str, first_tree['threshold']))}}};\n")
        f.write(f"const int FIRST_TREE_CHILD_LEFT[] = {{{', '.join(map(str, first_tree['children_left']))}}};\n")
        f.write(f"const int FIRST_TREE_CHILD_RIGHT[] = {{{', '.join(map(str, first_tree['children_right']))}}};\n")
        f.write(f"const double FIRST_TREE_VALUE[] = {{{', '.join(map(str, first_tree['value']))}}};\n\n")

        f.write("} // namespace ml\n")
        f.write("} // namespace canteen\n\n")
        f.write("#endif // CANTEEN_EMBEDDED_MODEL_DATA_HPP\n")

    print(f"[EXPORT] Generated embedded model header at {cpp_header_path}")

if __name__ == "__main__":
    export()
